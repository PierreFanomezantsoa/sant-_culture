@Injectable({ providedIn: 'root' })
export class LanguageService {
  readonly lang = signal<'fr' | 'mg'>(this.restore());
  constructor() {
    effect(() => {
      const language = this.lang();
      document.documentElement.lang = language;
      document.title = language === 'mg' ? 'AgriVeille — Fahasalaman’ny voly' : 'AgriVeille — Suivi sanitaire des cultures';
      try { localStorage.setItem('agriveille-language', language); } catch { /* Session-only preference. */ }
    });
  }
  private restore(): 'fr' | 'mg' {
    try { return localStorage.getItem('agriveille-language') === 'mg' ? 'mg' : 'fr'; } catch { return 'fr'; }
  }
  set(value: string) { if (value === 'fr' || value === 'mg') this.lang.set(value); }
  translate(value: unknown): string {
    const text = String(value ?? '');
    return this.lang() === 'mg' ? MALAGASY[text] ?? text : text;
  }
}

@Pipe({ name: 'tr', standalone: true, pure: false })
export class TranslatePipe implements PipeTransform {
  private language = inject(LanguageService);
  transform(value: unknown) { return this.language.translate(value); }
}
